"""End-to-end GUI benchmark (offscreen Qt): duration and memory of each stage of a typical session

usage: python bench.py DATA_DIR NAME [plugin ...]

DATA_DIR/NAME.{wav,json,neur} are generated by gen_data.py. Only the given plugins are selected (all of
them by default). Set BENCH_NO_WAVELET=1 to leave the wavelet plugin out.

Every stage prints a "STAGE" line as soon as it is done (duration, resident memory and peak resident
memory), so a run killed by a memory limit still shows how far it got; a final "BENCH" line gives
all the results as JSON.
"""

from __future__ import annotations

import json
import os
import pathlib
import resource
import sys
import time
from collections.abc import Callable
from typing import Any

import psutil

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
if os.environ.get("BENCH_NO_WAVELET"):
    sys.modules["wavelet_prosody_toolkit"] = None  # type: ignore[assignment]  # makes the plugin unavailable

RESULTS: dict[str, Any] = {}
PROCESS = psutil.Process()


def rss_mb() -> float:
    """Return the resident memory of the process

    Returns
    -------
    float
        The resident memory in MB
    """
    return PROCESS.memory_info().rss / 2**20


def stage(key: str, function: Callable[[], Any]) -> Any:
    """Run and measure one stage of the benchmark

    Parameters
    ----------
    key : str
        The name of the stage
    function : callable
        The stage

    Returns
    -------
    Any
        What the stage returns
    """
    start = time.perf_counter()
    result = function()
    RESULTS[key] = {
        "s": round(time.perf_counter() - start, 3),
        "rss_mb": round(rss_mb()),
        "peak_mb": round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024),
    }
    print(f"STAGE {key:40s} {RESULTS[key]}", flush=True)
    return result


def main(data: str, name: str, only: list[str]) -> None:
    """Run the benchmark

    Parameters
    ----------
    data : str
        The directory of the generated data
    name : str
        The base name of the data files
    only : list(str)
        The plugins to select (all of them if empty)
    """
    RESULTS["python_rss_mb"] = round(rss_mb())
    stage("import", lambda: (__import__("spiny.ui"), __import__("spiny.main")))

    import spiny.ui as ui
    from pyqtgraph.Qt import QtWidgets
    from spiny.annotations import get_controller
    from spiny.core import player

    app = QtWidgets.QApplication.instance() or QtWidgets.QApplication(["bench"])

    def frame(window: QtWidgets.QWidget) -> None:
        app.processEvents()
        window.grab()  # force a full render of the window

    stage("load_wav", lambda: player.loadNewWav(f"{data}/{name}.wav"))
    from spiny.raw_data import controller as raw

    raw.loadCoefficientFile(f"{data}/{name}.neur", -50, 5)
    ui.define_palette(app)
    stage("discover_plugins", ui.discover_plugins)
    window = stage("build_window", lambda: ui.GUIVisu())
    window.resize(1600, 1000)
    window.show()
    stage("first_paint", lambda: frame(window))
    annotations = pathlib.Path(f"{data}/{name}.json")
    stage("load_annotations", lambda: (get_controller().loadAnnotations(annotations), frame(window)))

    wav_plot = window._visualisation_area._dock_wav.wav_plot
    names = [window._plugin_list.itemText(i) for i in range(window._plugin_list.count())]
    names = [n for n in names if not only or n in only]
    for plugin in names:
        stage(f"select {plugin}", lambda: (window._plugin_list.setCurrentText(plugin), frame(window)))

    def pan(start: float, width: float, step: float, nb_frames: int) -> None:
        wav_plot.setXRange(start, start + width, padding=0)
        frame(window)
        for i in range(nb_frames):
            position = start + (i + 1) * step
            wav_plot.setXRange(position, position + width, padding=0)
            frame(window)

    window._plugin_list.setCurrentText("Spectrogram" if "Spectrogram" in names else names[0])
    frame(window)
    duration = player.duration
    stage("pan full view x10", lambda: pan(0, duration, duration / 1000, 10))
    stage("pan 60s view x10", lambda: pan(duration / 4, 60, 2, 10))
    stage("pan 5s view x10", lambda: pan(duration / 4, 5, 0.25, 10))
    stage("colormap change", lambda: (window._cmap_list.setCurrentText("magma"), frame(window)))
    print("BENCH " + json.dumps(RESULTS), flush=True)
    app.quit()


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
